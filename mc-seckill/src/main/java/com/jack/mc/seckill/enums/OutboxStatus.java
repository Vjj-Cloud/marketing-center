package com.jack.mc.seckill.enums;

/**
 * 本地消息表状态。
 * <p>
 * 用枚举而不是裸数字，是因为这些状态会出现在对账 SQL、告警文案、文档三处，
 * 一旦有人记错「2 是已消费还是已回滚」，对账结论就会反。
 */
public enum OutboxStatus {

    /** 已落库，尚未拿到 broker 确认 */
    PENDING(0),

    /** broker 已确认收到（SEND_OK），但还不确定消费端是否落库 */
    SENT(1),

    /** 已确认消费成功（订单表里能查到） */
    CONSUMED(2),

    /** 人工确认后已回滚库存（只能由管理接口写入，补偿任务不再自动进入） */
    ROLLED_BACK(3),

    /**
     * 重试耗尽，仍无法确认消息是否被消费——<b>库存保留，等人工核对</b>。
     * <p>
     * 这是第二轮评审改出来的状态。原来重试耗尽后直接回滚库存，
     * 依据只有「此刻查不到订单」，但「查不到」不等于「不会有」：
     * 消息可能早已投递成功，只是消费者积压到重试窗口之后才处理。
     * 那时库存已经还回去、订单又落了库 —— 一件货卖两次。
     * <p>
     * 现在的取舍是：宁可少卖（库存被占着、用户没订单，人工退掉），
     * 也不能超卖（用户付了钱拿不到货）。少卖是可用性问题，超卖是资损。
     * <p>
     * 这个状态不会永远停着：复查任务发现订单确实落了库会自动转成 CONSUMED，
     * 真没有订单的才需要人工处理。
     */
    NEEDS_REVIEW(4),

    /**
     * 人工回滚执行中（<b>过渡态</b>，只能由管理接口用 CAS 从 NEEDS_REVIEW 抢到）。
     * <p>
     * <b>为什么需要这个中间态（第三轮评审 P1）</b>：人工回滚要做三件事——
     * 查订单、回滚 Redis、改状态。三步之间消费者仍可能落库：
     * 查订单时没有、回滚前订单提交了，最后就是「库存还了 + 订单落了」。
     * <p>
     * 用一次 {@code UPDATE ... SET status=5 WHERE id=? AND status=4} 做互斥：
     * 只有抢到 5 的人才有资格继续。而订单落库事务里也锁同一行（FOR UPDATE），
     * 两边通过这一行数据库记录串行化，不再有「检查完又被插队」的窗口。
     * <p>
     * 抢到 5 之后无论成功失败都必须离开这个状态：
     * 回滚成功 → 3；发现订单 → 2；Redis 故障 → 退回 4 等重试。
     * 它不会长期停留，所以复查任务只需要看 4，不用关心 5。
     */
    ROLLING_BACK(5),

    /**
     * 抢购已在入口被中止（<b>墓碑态</b>）。
     * <p>
     * 触发的场景：扣减被兜底任务接管、或确认扣减时 Redis 不可信，
     * 主流程撤销了这条本地消息并归还了库存。
     * <p>
     * <b>为什么留墓碑而不是物理删除</b>：删除和消息投递之间有一个无法消除的窗口——
     * 补偿任务可能刚好读到 status=0 并发了出去。行被删掉之后，
     * 消费者查不到任何预留记录，会照常建单；而库存早已归还，就是超卖。
     * 留一条 status=6 的记录，消费者在落库事务里读到它就能拒绝，
     * 这个窗口才真正闭合。
     * <p>
     * 它不影响用户重试：撞 uk_user_activity 时若撞上的是 3 或 6，
     * 说明那一单本就不成立，复用该行重新参与即可。
     */
    ABORTED(6),

    /**
     * 订单消费者已在数据库事务内认领这条消息，正在插单和扣库存。
     * <p>
     * 该状态只在消费者事务未提交时可见；事务成功提交后变为 CONSUMED，
     * 失败回滚则恢复原状态。它让入口中止与消费者落库通过同一行互斥，
     * 避免消费者先读到 PENDING、入口随后写 ABORTED 并回滚库存的超卖窗口。
     */
    CONSUMING(7);

    private final int code;

    OutboxStatus(int code) {
        this.code = code;
    }

    public int getCode() {
        return code;
    }
}
