-- =============================================================
-- 扣减回滚：把「已购买标记 + 库存 + 待确认标记」三样一起还原
-- KEYS[1] = seckill:{activityId}:stock
-- KEYS[2] = seckill:{activityId}:bought
-- KEYS[3] = seckill:{activityId}:pending
-- ARGV[1] = userId
-- ARGV[2] = pending member（userId:reservationId）
--
-- 返回值： 1 = 确实把库存加回去了
--          0 = 这个用户本来就不在买家集合里（无需回滚）
--         -1 = 用户确实被移出了买家集合，但库存 key 已过期（活动结束），无处可还
--
-- ★ 为什么要区分 0 和 -1（第三轮评审 P1）：
--   调用方原来只拿到 true/false，把「无需回滚」和「Redis 故障」混成一个 false，
--   于是人工回滚接口在 Redis 挂掉时照样把记录标成「已回滚」——
--   状态显示已还库存，实际一件没还，对账时才会发现，而那时已经过去好几天。
--   现在 0 / -1 都是「安全无操作」，异常才是「基础设施失败」，
--   三者语义分开，管理接口才能在失败时保留 NEEDS_REVIEW 让人重试。
--
-- 为什么回滚也要用 Lua：
--   SREM / INCR / ZREM 如果分三次发，中间宕机就会变成「库存加回来了，
--   但用户还留在买家集合里」——这个用户从此再也抢不到这件商品，
--   而且客服查不出原因。
--
-- ★ 幂等的关键：只有 SREM 真删掉了成员，才允许 INCR。
--   第一版是无条件 INCR，于是同一个用户被回滚两次库存就多两件：
--     · 主流程落库失败回滚一次，补偿任务判定超时又回滚一次；
--     · 重试链路上重复触发的回滚；
--     · 人工复核回滚之后，兜底任务又跑了一遍。
--   这些都是真实会发生的，一旦库存虚增，就是直接超卖资损。
--   SREM 的返回值天然就是「我到底改没改状态」的凭据，用它做幂等开关，
--   比在应用层查一次「是否已回滚」更可靠——那又多了一次往返和一个窗口。
--
-- ★ 为什么还要检查 stock key 是否存在：
--   活动结束后库存 key 会过期。此时兜底任务若对一条历史记录执行回滚，
--   无条件 INCR 会凭空创建一个没有 TTL 的 "1"，变成一条永远清不掉的脏数据，
--   下次同 id 的活动复用这个 key 就直接多卖一件。宁可这次不加库存。
-- =============================================================

local removed = redis.call('SREM', KEYS[2], ARGV[1])

local result
if removed == 0 then
    -- 用户本来就不在买家集合里：重复回滚，什么都不做
    result = 0
elseif redis.call('EXISTS', KEYS[1]) == 0 then
    -- 用户确实被移出了买家集合，但库存 key 已经过期（活动结束），无处可还。
    -- 单独返回 -1，是为了让调用方能区分「安全无操作」和「Redis 故障」：
    -- 两种情况都不该重试，但只有后者需要保持待复核状态。
    result = -1
else
    redis.call('INCR', KEYS[1])
    result = 1
end

-- 无论是否加回库存，待确认标记都要清掉：
-- 这条扣减已经有结论了（要么回滚、要么已落库），不该再被兜底任务扫到。
redis.call('ZREM', KEYS[3], ARGV[2])

return result
