-- =============================================================
-- 第三轮评审修复：本地消息表增加「回滚执行中」状态
--
-- status 语义（完整版）：
--   0 PENDING      已落库，尚未拿到 broker 确认
--   1 SENT         broker 已确认收到，还不确定是否消费
--   2 CONSUMED     订单表里能查到，确认消费
--   3 ROLLED_BACK  人工确认后已回滚库存
--   4 NEEDS_REVIEW 重试耗尽，库存保留等人工
--   5 ROLLING_BACK 人工回滚执行中（过渡态，靠 CAS 4->5 抢到）
--   6 ABORTED      抢购已在入口中止（墓碑，消费者据此拒绝落库）
--
-- 5 的作用：给「查订单 / 回滚 Redis / 改状态」这三步加一个数据库层面的互斥点。
-- 没有它，消费者可能在「查订单」之后把订单插进来，最后库存还了、订单也落了。
--
-- 可重复执行（只改列注释；索引由 03 脚本创建）。
-- =============================================================

ALTER TABLE seckill_outbox
    MODIFY COLUMN status TINYINT NOT NULL DEFAULT 0
        COMMENT '0待投递 1已投递 2已消费 3人工回滚 4待人工复核 5回滚执行中 6已中止';

